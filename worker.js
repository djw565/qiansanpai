// 自动判断是否为概念类问题
function isConceptQuestion(q) {
  const patterns = [
    /^什么是/, /是什么意思/, /怎么理解/, /什么叫/,
    /解释一下/, /讲讲/, /检索/, /查找/, /知识库/, /概念/,
  ];
  const isShortAndImpersonal = q.length < 30 && !/我/.test(q);
  return patterns.some(p => p.test(q)) || isShortAndImpersonal;
}
